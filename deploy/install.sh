#!/usr/bin/env bash
# globalvpn — one-server test install (Ubuntu 24.04, run as root from /opt/globalvpn):
#
#   sudo bash /opt/globalvpn/deploy/install.sh
#
# Safe to re-run: existing secrets, keys and settings are kept; services are updated.
# Installs: Docker, WireGuard (wg0), firewall (own nftables table), the app stack
# (Caddy/HTTPS, API, workers, Telegram bot, Postgres, Redis) and the node agent.
set -euo pipefail

REPO=/opt/globalvpn
DEPLOY=$REPO/deploy
ENV_FILE=$DEPLOY/.env.prod
SECRETS=$DEPLOY/secrets
WG_DIR=/etc/wireguard
ETC=/etc/globalvpn
COMPOSE=(docker compose -f "$DEPLOY/docker-compose.prod.yml" --env-file "$ENV_FILE")
APP_UID=10001  # fixed uid of the app user in backend/Dockerfile

say()  { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
warn() { printf '\033[1;33mWARN: %s\033[0m\n' "$*" >&2; }
die()  { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "run as root: sudo bash $0"
[[ -d $REPO/backend && -d $REPO/node-agent ]] || die "copy the project to $REPO first"
. /etc/os-release
[[ ${ID:-} == ubuntu && ${VERSION_ID:-} == 24.04 ]] || warn "tested on Ubuntu 24.04 only (found ${PRETTY_NAME:-unknown})"

env_get() { [[ -f $ENV_FILE ]] && grep -E "^$1=" "$ENV_FILE" | tail -1 | cut -d= -f2- || true; }

ask() {  # ask VAR "question" [default] [secret]
  local var=$1 q=$2 def=${3:-} secret=${4:-} cur val
  cur=$(env_get "$var"); [[ -n $cur ]] && def=$cur
  while true; do
    if [[ -n $secret ]]; then
      read -r -s -p "$q${def:+ [saved]}: " val; echo
    else
      read -r -p "$q${def:+ [$def]}: " val
    fi
    val=${val:-$def}
    [[ -n $val || $var == CRYPTOBOT_API_TOKEN ]] && break
    echo "required"
  done
  printf -v "$var" '%s' "$val"
}

# --------------------------------------------------------------------------- packages
say "Installing packages (Docker, WireGuard, nftables)"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -y -q docker.io docker-compose-v2 wireguard-tools nftables iptables python3 \
  curl openssl ca-certificates age
systemctl enable --now docker

# --------------------------------------------------------------------------- questions
WAN_IF=$(ip -4 route show default | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}')
DETECTED_V4=$(ip -4 -o addr show dev "$WAN_IF" scope global | awk '{print $4}' | cut -d/ -f1 | head -1)
DETECTED_V6=$(ip -6 -o addr show dev "$WAN_IF" scope global 2>/dev/null | awk '{print $4}' | cut -d/ -f1 | head -1 || true)

say "A few questions (Enter keeps the value in [brackets])"
ask DOMAIN "Domain for this server (e.g. myvpn.duckdns.org)"
ask PUBLIC_IPV4 "Public IPv4 of this server" "$DETECTED_V4"
ask TELEGRAM_BOT_TOKEN "Telegram bot token from @BotFather" "" secret
ask TELEGRAM_BOT_USERNAME "Bot username without @"
ask CRYPTOBOT_API_TOKEN "Crypto Pay token from @CryptoTestnetBot (Enter to skip payments)" "" secret
ask NODE_COUNTRY "Country code of this server (DE, NL, FI, ...)" "DE"
ask NODE_CITY "City" "Frankfurt"
ask ADMIN_EMAIL "Your email for the admin panel /admin/ (no mail is sent, it is your login)"
[[ $ADMIN_EMAIL =~ ^[^@[:space:]]+@[^@[:space:]]+\.[A-Za-z]{2,}$ ]] || die "email looks wrong: $ADMIN_EMAIL"
ADMIN_ALLOWED_IPS=$(env_get ADMIN_ALLOWED_IPS)  # optional, e.g. "203.0.113.7/32 2001:db8::/48"
APP_NAME=$(env_get APP_NAME); [ "$APP_NAME" = "VpnHub" ] && APP_NAME=""  # old working name
APP_NAME=${APP_NAME:-KingKong VPN}
TELEGRAM_BOT_USERNAME=${TELEGRAM_BOT_USERNAME#@}
[[ $DOMAIN =~ ^[A-Za-z0-9.-]+\.[A-Za-z]{2,}$ ]] || die "domain looks wrong: $DOMAIN"

resolved=$(getent ahostsv4 "$DOMAIN" | awk 'NR==1{print $1}' || true)
[[ $resolved == "$PUBLIC_IPV4" ]] || warn "$DOMAIN resolves to '${resolved:-nothing}', not $PUBLIC_IPV4 — HTTPS will fail until DNS points here"

# --------------------------------------------------------------------------- secrets
say "Secrets"
install -d -m 0750 "$SECRETS" "$ETC"
keep_or() { local v; v=$(env_get "$1"); [[ -n $v ]] && echo "$v" || eval "$2"; }
POSTGRES_PASSWORD=$(keep_or POSTGRES_PASSWORD "openssl rand -hex 24")
REFRESH_TOKEN_PEPPER=$(keep_or REFRESH_TOKEN_PEPPER "openssl rand -hex 32")
DATA_ENCRYPTION_KEY=$(keep_or DATA_ENCRYPTION_KEY "openssl rand -base64 32")
if [[ ! -f $SECRETS/jwt_ed25519_private.pem ]]; then
  openssl genpkey -algorithm ed25519 -out "$SECRETS/jwt_ed25519_private.pem"
  openssl pkey -in "$SECRETS/jwt_ed25519_private.pem" -pubout -out "$SECRETS/jwt_ed25519_public.pem"
fi
chown -R "$APP_UID:$APP_UID" "$SECRETS"
chmod 0400 "$SECRETS/jwt_ed25519_private.pem"; chmod 0444 "$SECRETS/jwt_ed25519_public.pem"
chmod 0750 "$SECRETS"

umask 077
cat > "$ENV_FILE" <<EOF
# Generated by deploy/install.sh — contains secrets, keep it private (mode 600).
APP_ENV=staging
APP_NAME=$APP_NAME
DOMAIN=$DOMAIN
PUBLIC_WEB_URL=https://$DOMAIN
PUBLIC_API_URL=https://$DOMAIN
ADMIN_WEB_URL=https://$DOMAIN
CORS_ALLOWED_ORIGINS=https://$DOMAIN
POSTGRES_HOST=postgres
POSTGRES_DB=globalvpn
POSTGRES_USER=globalvpn
POSTGRES_PASSWORD=$POSTGRES_PASSWORD
REDIS_URL=redis://redis:6379/0
CELERY_BROKER_URL=redis://redis:6379/1
CELERY_RESULT_BACKEND=redis://redis:6379/2
JWT_PRIVATE_KEY_FILE=/run/secrets/jwt_ed25519_private.pem
JWT_PUBLIC_KEY_FILE=/run/secrets/jwt_ed25519_public.pem
REFRESH_TOKEN_PEPPER=$REFRESH_TOKEN_PEPPER
DATA_ENCRYPTION_KEY=$DATA_ENCRYPTION_KEY
# Email isn't configured for the Telegram test (accounts are Telegram-only).
EMAIL_DELIVERY=sync
SMTP_HOST=127.0.0.1
SMTP_PORT=25
TELEGRAM_BOT_TOKEN=$TELEGRAM_BOT_TOKEN
TELEGRAM_BOT_USERNAME=$TELEGRAM_BOT_USERNAME
TELEGRAM_DELIVERY=celery
CRYPTOBOT_API_TOKEN=$CRYPTOBOT_API_TOKEN
CRYPTOBOT_NETWORK=testnet
CRYPTOBOT_ACCEPTED_ASSETS=GRAM,USDC
VPN_TUNNEL_IPV4_POOL=10.64.0.0/10
VPN_TUNNEL_IPV6_POOL=fd00:6476:706e::/48
VPN_TUNNEL_RESERVED_ADDRESSES=16
VPN_CLIENT_DNS=1.1.1.1,2606:4700:4700::1111
NODE_COUNTRY=$NODE_COUNTRY
NODE_CITY=$NODE_CITY
PUBLIC_IPV4=$PUBLIC_IPV4
ADMIN_EMAIL=$ADMIN_EMAIL
# Admin panel and staff API only from these networks (space-separated CIDRs); empty = anywhere.
ADMIN_ALLOWED_IPS=$ADMIN_ALLOWED_IPS
EOF
chmod 600 "$ENV_FILE"
umask 022

# --------------------------------------------------------------------------- WireGuard
say "WireGuard (wg0)"
install -d -m 0700 "$WG_DIR"
if [[ ! -f $WG_DIR/wg0.key ]]; then
  (umask 077; wg genkey > "$WG_DIR/wg0.key")
fi
WG_PUB=$(wg pubkey < "$WG_DIR/wg0.key")
(umask 077; cat > "$WG_DIR/wg0.conf" <<EOF
# Managed by globalvpn install.sh. Peers are added/removed live by the node agent.
[Interface]
Address = 10.64.0.1/10, fd00:6476:706e::1/48
ListenPort = 51820
PrivateKey = $(cat "$WG_DIR/wg0.key")
SaveConfig = false
EOF
)
cat > /etc/sysctl.d/90-globalvpn.conf <<EOF
net.ipv4.ip_forward = 1
net.ipv6.conf.all.forwarding = 1
# keep accepting router advertisements on the uplink despite forwarding=1
net.ipv6.conf.$WAN_IF.accept_ra = 2
EOF
sysctl -q --system
systemctl enable -q wg-quick@wg0
systemctl restart wg-quick@wg0

# --------------------------------------------------------------------------- firewall
say "Firewall"
if [[ -n $DETECTED_V6 ]]; then
  V6_POLICY='# this host has IPv6: tunnel IPv6 is NATed out'
else
  V6_POLICY='iifname "wg0" meta nfproto ipv6 reject with icmpv6 type admin-prohibited comment "no IPv6 uplink: fail fast, never leak"'
  warn "no global IPv6 on $WAN_IF — clients' IPv6 is blocked inside the tunnel (no leak)"
fi
sed -e "s/@WAN@/$WAN_IF/g" -e "s|@V6_POLICY@|$V6_POLICY|" "$DEPLOY/firewall.nft.tmpl" > "$ETC/firewall.nft"
nft -c -f "$ETC/firewall.nft"
install -m 0644 "$DEPLOY/globalvpn-firewall.service" /etc/systemd/system/
chmod +x "$DEPLOY/docker-user.sh"
systemctl daemon-reload
systemctl enable -q globalvpn-firewall
systemctl restart globalvpn-firewall

# --------------------------------------------------------------------------- app stack
say "Building and starting the app (first build takes a few minutes)"
"${COMPOSE[@]}" up -d --build
for _ in $(seq 1 60); do
  curl -fsS http://127.0.0.1:8000/health/ready >/dev/null 2>&1 && break
  sleep 3
done
curl -fsS http://127.0.0.1:8000/health/ready >/dev/null || die "API didn't become ready: ${COMPOSE[*]} logs backend"
systemctl restart globalvpn-firewall  # Docker may have recreated its chains

cli() { "${COMPOSE[@]}" exec -T backend python -m app.cli "$@"; }
cli bootstrap-catalog
cli set-setting access.invite_only true >/dev/null
cli set-setting trial.enabled false >/dev/null
ADMIN_LINE="account $ADMIN_EMAIL exists (new password: cd $DEPLOY && ${COMPOSE[*]} exec backend python -m app.cli create-staff $ADMIN_EMAIL superadmin)"
if [[ ! -f $ETC/admin-created ]]; then
  say "Admin panel account"
  ADMIN_OUT=$(cli create-staff "$ADMIN_EMAIL" superadmin) || die "could not create the admin account"
  ADMIN_PASSWORD=$(sed -n 's/^one-time password: //p' <<<"$ADMIN_OUT")
  touch "$ETC/admin-created"
  ADMIN_LINE="$ADMIN_EMAIL / one-time password: $ADMIN_PASSWORD  (shown once: sign in now and set up 2FA)"
fi

# --------------------------------------------------------------------------- node agent
say "Registering this server as a VPN node"
REG=$(cli node-register --hostname "$(hostname -f 2>/dev/null || hostname)" --country "$NODE_COUNTRY" \
  --city "$NODE_CITY" --ipv4 "$PUBLIC_IPV4" ${DETECTED_V6:+--ipv6 "$DETECTED_V6"} \
  --port 51820 --wg-public-key "$WG_PUB")
NODE_ID=$(python3 -c 'import json,sys; print(json.loads(sys.stdin.read())["server_id"])' <<<"$REG")
NODE_TOKEN=$(python3 -c 'import json,sys; print(json.loads(sys.stdin.read())["token"])' <<<"$REG")
id globalvpn-agent >/dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin globalvpn-agent
(umask 027; cat > "$ETC/agent.env" <<EOF
API_URL=http://127.0.0.1:8000
NODE_ID=$NODE_ID
NODE_TOKEN=$NODE_TOKEN
WG_IFACE=wg0
TUNNEL_POOLS=10.64.0.0/10,fd00:6476:706e::/48
EOF
)
chown root:globalvpn-agent "$ETC/agent.env"; chmod 0640 "$ETC/agent.env"
chmod 0755 "$ETC"
install -m 0644 "$REPO/node-agent/systemd/globalvpn-agent.service" /etc/systemd/system/
systemctl daemon-reload
systemctl enable -q globalvpn-agent
systemctl restart globalvpn-agent
sleep 5
systemctl is-active --quiet globalvpn-agent || die "agent failed: journalctl -u globalvpn-agent -n 50"

if [[ -n $CRYPTOBOT_API_TOKEN ]]; then
  say "Checking @CryptoBot"
  cli cryptobot-check || warn "Crypto Pay check failed — payments won't work until fixed"
fi

say "Daily database backup"
# strip CRLF in case the project was copied from Windows without .gitattributes
sed -i 's/\r$//' "$DEPLOY"/*.sh
install -m 0755 "$DEPLOY/backup.sh" /etc/cron.daily/globalvpn-backup
/etc/cron.daily/globalvpn-backup && echo "backup OK: /var/backups/globalvpn"

say "Invite codes (single use, 30 days of access)"
cli create-invites --count 10 --days 30 | tee -a "$ETC/invites.txt"

cat <<EOF

$(printf '\033[1;32m')Done.$(printf '\033[0m')
  Mini App:        https://$DOMAIN/app/
  Admin panel:     https://$DOMAIN/admin/
                   $ADMIN_LINE
  Bot:             https://t.me/$TELEGRAM_BOT_USERNAME  (send /start)
  Invites saved:   $ETC/invites.txt   (more: cd $DEPLOY && ${COMPOSE[*]} exec backend python -m app.cli create-invites --count 5)
  Payments webhook (optional, in @CryptoTestnetBot → Crypto Pay → My Apps → Webhooks):
                   https://$DOMAIN/api/v1/webhooks/cryptobot
  Logs:            cd $DEPLOY && docker compose -f docker-compose.prod.yml logs -f backend bot
                   journalctl -u globalvpn-agent -f
  Backups:         /var/backups/globalvpn (daily, 14 days) — encrypt them: put an age public key in /etc/globalvpn/backup-recipients
  Update later:    copy the new project files to $REPO and run this script again
  Firewall in your VPS panel (recommended): allow only TCP 22, 80, 443 and UDP 51820, 443.
EOF
